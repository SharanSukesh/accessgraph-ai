"""Writes the Lumenvale fixture part for roadmap 35b (role design mode).

Synthetic. What the impact preview needs to show real figures:
  - Account owner counts, 5,200 in all (the Account count Data Quality
    reports), given only to users who already own Opportunities, Leads,
    Cases or Contacts and weighted by their Opportunities. License Fit only
    looks at Account ownership when a user owns nothing, so it can't change.
  - Org-wide defaults, all Private (Contact controlled by parent), so a move
    changes both view and edit access.
  - A role-based sharing rule (EMEA Opportunities to Sales Operations, read)
    and a public group, "Regional Sales Directors", holding the three
    regional director role groups, so the preview has references to list.
Measured in a scratch run after PR #22: Health Report 41, 18 findings,
$183,180; License Fit $116,220; risk levels, anomalies and Priority Actions
unchanged. Deterministic.

    python research/demo_fixture/build_role_design_part.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "apps/backend"))
OUT = ROOT / "apps/backend/fixtures/synthetic_mid_market.parts/06-role-design.json"
ACCOUNT_TOTAL = 5200


def gid(prefix: str, n: int) -> str:
    return f"{prefix}{n:012d}DMO"  # 3 + 12 + 3 = 18 characters


def account_owners(owner_counts):
    owners = sorted({u for obj in ("Opportunity", "Lead", "Case", "Contact") for u in owner_counts.get(obj, {})})
    weights = [owner_counts.get("Opportunity", {}).get(u, 0) + 1 for u in owners]
    w = sum(weights)
    counts = {u: max(1, round(ACCOUNT_TOTAL * x / w)) for u, x in zip(owners, weights)}
    drift = ACCOUNT_TOTAL - sum(counts.values())
    for u in sorted(counts, key=lambda u: (-counts[u], u)):
        if not drift:
            break
        step = 1 if drift > 0 else -1
        if counts[u] + step >= 1:
            counts[u] += step
            drift -= step
    assert sum(counts.values()) == ACCOUNT_TOTAL
    return counts


def main() -> None:
    from app.ingestion.demo_orgs import load_fixture

    data = load_fixture("synthetic_mid_market")
    # Built from the fixture without this part, so re-running is stable.
    assert "Account" not in data["demo_live"]["owner_counts"] or OUT.exists()
    base_counts = {k: v for k, v in data["demo_live"]["owner_counts"].items() if k != "Account"}
    roles = {r["Name"]: r["Id"] for r in data["roles"]}

    def role_group(n, role, gtype):
        return {"Id": gid("00G", n), "Name": None, "Type": gtype, "DeveloperName": None, "RelatedId": roles[role]}

    ops = role_group(901, "Sales Operations", "Role")
    emea = role_group(902, "Sales Director, EMEA", "RoleAndSubordinatesInternal")
    directors = [role_group(903 + i, name, "Role") for i, name in enumerate(
        ["Sales Director, North America", "Sales Director, EMEA", "Sales Director, APAC"])]
    public = {"Id": gid("00G", 910), "Name": "Regional Sales Directors", "Type": "Regular",
              "DeveloperName": "Regional_Sales_Directors", "RelatedId": None}
    part = {
        "_source": "Roadmap 35b. Generated by research/demo_fixture/build_role_design_part.py; synthetic.",
        "demo_live": {"owner_counts": {"Account": account_owners(base_counts)}},
        "organization_wide_defaults": [
            {"SobjectType": o, "InternalSharingModel": m, "ExternalSharingModel": "Private"}
            for o, m in (("Account", "Private"), ("Opportunity", "Private"), ("Case", "Private"),
                         ("Contact", "ControlledByParent"), ("Lead", "Private"))
        ],
        "groups": [ops, emea, *directors, public],
        "group_members": [{"Id": gid("011", 901 + i), "GroupId": public["Id"], "UserOrGroupId": g["Id"]}
                          for i, g in enumerate(directors)],
        "sharing_rules": [{
            "Id": gid("02c", 901), "Name": "EMEA opportunities to Sales Operations", "SobjectType": "Opportunity",
            "RuleType": "OwnerBased", "AccessLevel": "Read", "SharedToType": "Role", "SharedToId": ops["Id"],
        }],
    }
    OUT.write_text(json.dumps(part, indent=1) + "\n")
    print(f"Account owners: {len(part['demo_live']['owner_counts']['Account'])}, total {ACCOUNT_TOTAL:,}")


if __name__ == "__main__":
    main()
