"""Writes the Lumenvale fixture part for roadmap item 4 (org code coverage).

Synthetic: 60 classes and 12 triggers with a realistic spread, 4 classes
and 2 triggers at 0%, org-wide 71% (below the 75% gate), test classes with
no coverage rows of their own, one class whose coverage was never recorded,
a last test run 40 days before the fixture date, and one class changed
after it. Deterministic (seeded).

    python research/demo_fixture/build_code_coverage_part.py
"""
import json
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "apps/backend/fixtures/synthetic_mid_market.parts/04-code-coverage.json"
FIXTURE_DATE = datetime(2026, 10, 14, 9, 0, tzinfo=timezone.utc)
LAST_RUN = FIXTURE_DATE - timedelta(days=40)
TARGET_PCT = 71.0

DOMAINS = ["Account", "Opportunity", "Quote", "Invoice", "Treasury", "Payroll", "Case", "Lead", "Territory",
           "Commission", "Renewal", "Contract", "Order", "Shipment", "Forecast"]
ROLES = ["Service", "Selector", "Handler", "Controller"]


def iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%S.000+0000")


def main() -> None:
    rng = random.Random(4)
    names = [f"{d}{r}" for d in DOMAINS for r in ROLES][:60]
    zero_classes = {"LegacyInvoiceSync", "OldQuotePdfGenerator", "TerritoryRebalanceBatch", "ManualShareCleanup"}
    names = names[:56] + sorted(zero_classes)
    # Apex names can't contain double underscores, so custom objects drop the __c.
    triggers = [f"{o}Trigger" for o in ["Account", "Opportunity", "Contact", "Lead", "Case", "Quote", "Invoice",
                                         "TreasuryAccount", "Order", "Contract", "Commission", "Shipment"]]
    zero_triggers = {"CommissionTrigger", "ShipmentTrigger"}

    items = []
    for i, name in enumerate(names):
        lines = rng.randint(40, 420)
        pct = 0.0 if name in zero_classes else min(1.0, max(0.35, rng.gauss(0.80, 0.14)))
        items.append({"id": f"01p0000000{i:04d}DMO", "name": name, "type": "class", "lines": lines, "pct": pct})
    for i, name in enumerate(triggers):
        lines = rng.randint(15, 120)
        pct = 0.0 if name in zero_triggers else min(1.0, max(0.5, rng.gauss(0.85, 0.1)))
        items.append({"id": f"01q0000000{i:04d}DMO", "name": name, "type": "trigger", "lines": lines, "pct": pct})

    # Scale the non-zero items so lines covered come to TARGET_PCT org-wide.
    total = sum(i["lines"] for i in items)
    want = TARGET_PCT / 100 * total
    have = sum(i["lines"] * i["pct"] for i in items)
    factor = want / have
    for it in items:
        it["covered"] = min(it["lines"], round(it["lines"] * it["pct"] * factor))
    drift = round(want) - sum(i["covered"] for i in items)
    for it in sorted(items, key=lambda i: -i["lines"]):
        if drift == 0:
            break
        step = 1 if drift > 0 else -1
        if 0 < it["covered"] + step <= it["lines"] and it["pct"] > 0:
            it["covered"] += step
            drift -= step

    out = []
    for it in items:
        modified = LAST_RUN - timedelta(days=rng.randint(5, 400))
        if it["name"] == "RenewalService":
            modified = LAST_RUN + timedelta(days=16)  # changed after the last test run
        out.append({"id": it["id"], "name": it["name"], "type": it["type"], "covered": it["covered"],
                    "uncovered": it["lines"] - it["covered"], "last_modified": iso(modified)})
    for i, name in enumerate([f"{n}Test" for n in names[:18]]):
        out.append({"id": f"01p0000001{i:04d}DMO", "name": name, "type": "class", "covered": None,
                    "uncovered": None, "last_modified": iso(LAST_RUN - timedelta(days=rng.randint(5, 400)))})
    out.append({"id": "01p0000002000DMO", "name": "LegacyBatchExporter", "type": "class", "covered": None,
                "uncovered": None, "last_modified": iso(LAST_RUN - timedelta(days=700))})

    covered = sum(i["covered"] or 0 for i in out)
    lines = sum((i["covered"] or 0) + (i["uncovered"] or 0) for i in out)
    part = {
        "_source": "Roadmap item 4. Generated by research/demo_fixture/build_code_coverage_part.py; synthetic.",
        "demo_live": {"code_coverage": {
            "org_wide_percent": round(covered / lines * 100),
            "last_test_run": iso(LAST_RUN),
            "items": out,
        }},
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(part, indent=1) + "\n")
    print(f"{len(out)} items, org-wide {covered / lines * 100:.2f}% -> {part['demo_live']['code_coverage']['org_wide_percent']}%")


if __name__ == "__main__":
    main()
